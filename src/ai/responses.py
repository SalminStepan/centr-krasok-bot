def glossary_reply(user_text: str) -> str | None:
    text = user_text.lower()
    for term in GLOSSARY_TERMS.values():
        if any(alias in text for alias in term.aliases):
            return term.explanation
    if "глоссар" not in text and "термин" not in text:
        return None

    lines = ["Короткий глоссарий:"]
    for name, term in GLOSSARY_TERMS.items():
        lines.append(f"{name.capitalize()}: {term.explanation}")
    return "\n\n".join(lines)
